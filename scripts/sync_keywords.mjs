// Writes grammar/keywords.js from the keyword lists of avenger-sql-syntax, so the grammar's
// reserved and non-reserved keywords are the Rust parser's.
//
// Usage: node scripts/sync_keywords.mjs --avenger-root PATH [--check]
//
// With --check, it writes nothing and fails when grammar/keywords.js differs from the lists.

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const argument = process.argv.indexOf("--avenger-root");
if (argument < 0 || !process.argv[argument + 1]) {
  throw new Error("usage: node scripts/sync_keywords.mjs --avenger-root PATH [--check]");
}
const avengerRoot = resolve(process.argv[argument + 1]);
const sourcePath = resolve(avengerRoot, "avenger-sql-syntax/src/syntax_kind.rs");
const source = readFileSync(sourcePath, "utf8");

// The lists are the `reserved: [...]` and `keywords: [...]` arms of the `syntax_kinds!` call,
// as entries `NAME_KW = "TEXT"`.
// The macro's own definition also has these arms, as patterns, so the list is the arm whose
// entries are keywords.
function list(arm) {
  const arms = [...source.matchAll(new RegExp(`\\n\\s*${arm}: \\[([\\s\\S]*?)\\n\\s*\\],`, "g"))];
  for (const match of arms) {
    const words = [...match[1].matchAll(/^\s*[A-Z_]+_KW = "([A-Z_]+)",/gm)].map(m => m[1]);
    if (words.length > 0) return words;
  }
  throw new Error(`no \`${arm}: [...]\` list of keywords in ${sourcePath}`);
}

const reserved = list("reserved");
const nonReserved = list("keywords");

const format = words => {
  const lines = [];
  let line = "";
  for (const word of words) {
    const item = `"${word}",`;
    if (line.length + item.length + 1 > 96) {
      lines.push(line);
      line = "";
    }
    line = line ? `${line} ${item}` : item;
  }
  lines.push(line);
  return lines.map(l => `  ${l}`).join("\n");
};

const output = `// Generated by scripts/sync_keywords.mjs from avenger-sql-syntax/src/syntax_kind.rs.
// Do not edit by hand.

// GoogleSQL's reserved keywords, which are names only in backticks and as argument names.
export const RESERVED = [
${format(reserved)}
];

// The keywords that are names wherever the keyword is not valid.
export const NON_RESERVED = [
${format(nonReserved)}
];
`;

const target = resolve(root, "grammar/keywords.js");
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // A missing file differs.
  }
  if (current !== output) {
    process.stderr.write(
      "grammar/keywords.js differs from avenger-sql-syntax; run node scripts/sync_keywords.mjs --avenger-root PATH\n",
    );
    process.exit(1);
  }
} else {
  writeFileSync(target, output);
}
